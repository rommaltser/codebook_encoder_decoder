def get_cluster_config(
    num_clusters: int = 6,
    labels_dict: Optional[Dict[str, Dict[str, str]]] = None,
    words_per_cluster: int = 24,
) -> Tuple[List[str], Dict[str, List[str]]]:
    """
    Returns (cluster_order, cluster_lexicon).
    If `labels_dict` is provided, inspects the actual keys/values in the JSON annotations
    so that any custom cluster names or lexicon tokens generated by Qwen2.5-VL are
    automatically incorporated while preserving a fixed vocabulary size per cluster.
    """
    default_order = CLUSTER_ORDER_8 if num_clusters == 8 else CLUSTER_ORDER_6[:num_clusters]
    lexicon = {c: list(CLUSTER_LEXICON[c][:words_per_cluster]) for c in default_order if c in CLUSTER_LEXICON}

    if not labels_dict:
        return default_order, lexicon

    # Discover candidate cluster keys from the first valid sample in labels_dict
    sample_keys: List[str] = []
    for _, val in labels_dict.items():
        if isinstance(val, dict):
            # Ignore metadata fields if present
            candidate = [
                k for k, v in val.items()
                if isinstance(v, str) and k not in ("image_path", "path", "id", "category", "split", "raw_response")
            ]
            if candidate:
                sample_keys = candidate
                break

    if all(c in sample_keys for c in default_order):
        active_order = default_order
    elif len(sample_keys) >= num_clusters:
        active_order = sample_keys[:num_clusters]
    else:
        active_order = default_order

    # Merge observed vocabulary from labels_dict into lexicon
    merged_lexicon: Dict[str, List[str]] = {}
    for c in active_order:
        base_words = list(CLUSTER_LEXICON.get(c, []))
        observed = sorted({
            str(v[c]).strip()
            for v in labels_dict.values()
            if isinstance(v, dict) and v.get(c) and isinstance(v.get(c), str)
        })
        # Start with observed words so every word in the dataset has a guaranteed valid index,
        # then pad or truncate to words_per_cluster using canonical words.
        combined: List[str] = []
        for w in observed + base_words:
            if w and w not in combined:
                combined.append(w)
        # Pad with synthetic placeholder tokens if fewer than words_per_cluster exist
        while len(combined) < words_per_cluster:
            combined.append(f"{c}_token_{len(combined)}")
        merged_lexicon[c] = combined[:words_per_cluster]

    return active_order, merged_lexicon

